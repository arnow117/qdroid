function timingSafeHexEqual(left: string, right: string): boolean {
  const leftBytes = Buffer.from(left, 'hex');
  const rightBytes = Buffer.from(right, 'hex');
  return leftBytes.byteLength === rightBytes.byteLength && timingSafeEqual(leftBytes, rightBytes);
}

async function readPrivateAssemblyReceipt(path: string): Promise<Buffer | undefined> {
  try {
    const before = await lstat(path);
    if (before.isSymbolicLink() || !before.isFile() || (before.mode & 0o777) !== 0o600) {
      return undefined;
    }
    const file = await open(path, fsConstants.O_RDONLY | fsConstants.O_NOFOLLOW);
    let bytes: Buffer;
    try {
      const opened = await file.stat();
      if (
        opened.dev !== before.dev ||
        opened.ino !== before.ino ||
        !opened.isFile() ||
        (opened.mode & 0o777) !== 0o600
      ) {
        return undefined;
      }
      bytes = await file.readFile();
      await file.sync();
    } finally {
      await file.close();
    }
    const after = await lstat(path);
    return after.dev === before.dev && after.ino === before.ino ? bytes : undefined;
  } catch {
    return undefined;
  }
}

