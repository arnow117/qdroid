async function durableWrite(
  path: string,
  value: unknown,
  openJournalFile: ResourceJournalFileOpener = openPrivateResourceJournalFile,
): Promise<void> {
  const temporary = `${path}.${randomUUID()}.tmp`;
  const file = await openJournalFile(temporary);
  const failures: unknown[] = [];
  try {
    await file.writeFile(`${JSON.stringify(value)}\n`, 'utf8');
    await file.sync();
  } catch (error) {
    failures.push(error);
  }
  try {
    await file.close();
  } catch (error) {
    failures.push(error);
  }
  throwIfJournalWriteFailures(failures, temporary);
  await rename(temporary, path);
  await syncDirectory(dirname(path));
}

