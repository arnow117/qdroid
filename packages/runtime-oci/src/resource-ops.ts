  private async stopConfiguredBoundaryProbe(
    guardian: SandboxGuardianClient,
    guardianExited: Promise<void> | undefined,
    guardianPid: number,
    guardianIdentity: Readonly<{ groupId: number; pid: number; processStart: string }>,
    resourceId: string,
    configuration: Readonly<{
      configurationAuthenticationTag?: string;
      configurationReceiptPath: string;
      creationReceiptPath: string;
      terminalReceiptPath: string;
    }>,
  ): Promise<ResourceCleanupEvidence> {
    const failures: unknown[] = [];
    try {
      await guardian.stop('stopped');
    } catch (error) {
      failures.push(error);
    }

    let completionConfirmed = false;
    try {
      completionConfirmed = (await guardian.completion).cleanupConfirmed;
    } catch (error) {
      failures.push(error);
    }

    const guardianSettled =
      guardianExited !== undefined &&
      (await waitForGuardianAndGroupExit(guardianExited, guardianPid, 1_000));
    const terminalConfirmed =
      configuration.configurationAuthenticationTag === undefined
        ? false
        : await this.readBoundaryProbeNoCreateTerminalReceipt(
            configuration.terminalReceiptPath,
            resourceId,
            guardianIdentity,
            configuration as Readonly<{
              configurationAuthenticationTag: string;
              configurationReceiptPath: string;
              creationReceiptPath: string;
              terminalReceiptPath: string;
            }>,
          );
    const cleanupConfirmed =
      failures.length === 0 && completionConfirmed && guardianSettled && terminalConfirmed;

    await this.updateResource(resourceId, {
      status: cleanupConfirmed ? 'confirmed' : 'unknown',
    });
    if (!cleanupConfirmed && failures.length > 0) {
      throw aggregateErrors(failures, 'Configured boundary probe cleanup did not settle.');
    }
    return cleanupConfirmed ? confirmedEvidence() : unknownEvidence();
  }

  private async stopIdleGuardian(
    guardian: SandboxGuardianClient,
    guardianExited: Promise<void> | undefined,
    guardianPid: number,
    resourceId: string,
    guardianIdentityPersisted: boolean,
  ): Promise<ResourceCleanupEvidence> {
    const idleExitRequested = guardian.requestIdleWorkerExit();
    const settled =
      !idleExitRequested || guardianExited === undefined
        ? false
        : await waitForGuardianAndGroupExit(guardianExited, guardianPid, 1_000);
    const status =
      idleExitRequested && settled && guardianIdentityPersisted ? 'confirmed' : 'unknown';
    await this.updateResource(resourceId, { status });
    return status === 'confirmed' ? confirmedEvidence() : unknownEvidence();
  }
