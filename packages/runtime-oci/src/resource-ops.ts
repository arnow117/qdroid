async function waitForGuardianAndGroupExit(
  guardianExited: Promise<void>,
  guardianPid: number,
  deadlineMs: number,
): Promise<boolean> {
  const deadline = Date.now() + deadlineMs;
  const exited = await Promise.race([
    guardianExited.then(() => true),
    delay(deadlineMs).then(() => false),
  ]);
  if (!exited) {
    return false;
  }

  while (Date.now() < deadline) {
    try {
      process.kill(-guardianPid, 0);
    } catch (error) {
      if (isMissingProcessGroup(error)) {
        return true;
      }
      return false;
    }
    await delay(25);
  }

  return false;
}

