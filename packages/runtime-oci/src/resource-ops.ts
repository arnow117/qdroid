/** Serializes non-cancellable journal writes and seals their final ordering. */
class ResourceJournalMutations {
  private closing = false;
  private serial: Promise<void> = Promise.resolve();
  private failure: unknown;

  public mutate(operation: () => Promise<void>): Promise<void> {
    if (this.closing) {
      return Promise.reject(new Error('The managed resource journal is sealed.'));
    }
    if (this.failure !== undefined) {
      return Promise.reject(this.failure);
    }

    const mutation = this.serial.then(operation);
    this.serial = mutation.then(undefined, (error) => {
      this.failure ??= error;
      throw error;
    });
    // The operation caller and `seal()` preserve the rejection. This observer
    // only prevents Node from treating a still-live raw write as unhandled.
    void this.serial.catch(() => undefined);
    return mutation;
  }

  public async seal(): Promise<void> {
    this.closing = true;
    await this.serial;
  }
}

