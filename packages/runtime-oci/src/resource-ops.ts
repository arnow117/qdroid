  public assembleFixed(input: PreparedAssemblyInput): Promise<ImageAssemblyResult> {
    this.assertAccepting();
    // Claim the opaque input synchronously. A second caller gets the same
    // in-flight or terminal result and therefore cannot create a second
    // stopped container or retry an uncertain commit.
    const material = readPreparedAssemblyInput(this.options.owner, input);
    const existing = this.assemblyOperations.get(input);
    if (existing !== undefined) {
      return existing;
    }

    const operationLease = beginBuildSessionOperation(this.options.owner);
    const operation = this.startManagedAssembly(input, material);
    this.assemblyOperations.set(input, operation);
    this.observeOperation(operation, operationLease);
    return operation;
  }

  public async close(): Promise<void> {
    if (this.closePromise !== undefined) {
      return this.closePromise;
    }

    if (this.closed) {
      return;
    }

    this.admissionClosed = true;
    this.closePromise = this.closeInternal();
    return this.closePromise;
  }

